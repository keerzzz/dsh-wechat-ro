import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { captureArchiveMetadata, runArchiveQuery, readArchiveResource } from '../lib/archive-query-worker.js';
import { mediaCandidates } from '../lib/content-analysis.js';
const result = spawnSync(process.env.WECHAT_TEST_PYTHON || 'python3', [fileURLToPath(new URL('../../scripts/test_content_index.py', import.meta.url))], { encoding: 'utf8' });
assert.equal(result.status, 0, result.stdout + result.stderr);
const root = mkdtempSync(join(tmpdir(), 'wechat-content-synthetic-'));
try {
  for (const name of ['content', 'contact', 'message']) mkdirSync(join(root, name));
  let db = new DatabaseSync(join(root, 'content/content.db'));
  db.exec('CREATE TABLE records(record_ref TEXT,kind TEXT,talker TEXT,ts INTEGER,title TEXT,content TEXT,url TEXT,metadata TEXT)');
  const insert = db.prepare('INSERT INTO records VALUES(?,?,?,?,?,?,?,?)');
  insert.run('a'.repeat(32), 'moments', 'alpha', 1700000000, '', 'needle 原文', '', '{}');
  insert.run('b'.repeat(32), 'favorites', 'beta', 1700000001, '收藏', 'needle 私人内容', '', '{}');
  insert.run('c'.repeat(32), 'miniprogram', 'alpha', null, '地图 needle', '', 'https://example.test', '{}');
  db.close();
  db = new DatabaseSync(join(root, 'contact/contact.db')); db.exec("CREATE TABLE contact(username TEXT,remark TEXT); INSERT INTO contact VALUES('alpha','甲'),('beta','乙')"); db.close();
  db = new DatabaseSync(join(root, 'message/message_resource.db'));
  db.exec("CREATE TABLE ChatName2Id(user_name TEXT); INSERT INTO ChatName2Id VALUES('alpha'),('beta'); CREATE TABLE MessageResourceInfo(message_id INTEGER,chat_id INTEGER,message_local_id INTEGER,message_create_time INTEGER,message_local_type INTEGER,packed_info BLOB)");
  const resource = db.prepare('INSERT INTO MessageResourceInfo VALUES(?,?,?,?,?,?)');
  const packed = Buffer.concat([Buffer.from('12220a20', 'hex'), Buffer.from('c'.repeat(32))]);
  resource.run(1, 1, 12, 1700000000, 3, packed); resource.run(2, 1, 13, 1700000001, 43, packed); resource.run(3, 2, 14, 1700000002, 3, packed);
  db.close();
  const expected = captureArchiveMetadata(root);
  const read = (query, scope = {}) => runArchiveQuery({ root, expected, scope: { allConversations: false, talkers: ['alpha'], fromTs: null, toTs: null, ...scope }, query: { limit: 20, offset: 0, fromTs: null, toTs: null, ...query } });
  const page = read({ action: 'search', sourceKind: 'moments', query: 'needle' });
  assert.equal(page.returned, 1); assert.equal(page.rows[0].citation.recordRef, 'a'.repeat(32)); assert.equal(page.rows[0].localTime, '2023-11-15T06:13:20+08:00');
  assert.equal(read({ action: 'search', sourceKind: 'favorites', query: 'needle' }).returned, 0);
  assert.equal(read({ action: 'content', sourceKind: 'miniprogram', fromTs: 1699990000 }).returned, 0);
  assert.equal(read({ action: 'content', sourceKind: 'miniprogram' }).returned, 1);
  const stats = read({ action: 'contentStats' }, { allConversations: true, talkers: [] }).rows;
  assert.equal(stats.find(row => row.sourceKind === 'contacts').total, 2);
  assert.equal(stats.find(row => row.sourceKind === 'favorites').total, 1);
  const scope = { allConversations: false, talkers: ['alpha'], fromTs: null, toTs: null };
  const media = read({ action: 'media', sourceKind: 'messages' });
  assert.equal(media.returned, 2); assert.equal(media.rows[0].sourceKind, 'video');
  const image = readArchiveResource(root, scope, { talker: 'alpha', localId: '12', ts: 1700000000 });
  assert.equal(image.mediaHash, 'c'.repeat(32));
  assert.equal(image.citation.recordRef, media.rows[1].citation.recordRef);
  assert.throws(() => readArchiveResource(root, scope, { talker: 'beta', localId: '14', ts: 1700000002 }), /scope-forbidden/);
  assert.throws(() => readArchiveResource(root, scope, { talker: 'alpha', localId: '12', ts: 1700000001 }), /unsupported-content/);
  assert.throws(() => readArchiveResource(root, { ...scope, fromTs: 1700000001 }, { talker: 'alpha', localId: '12', ts: 1700000000 }), /scope-forbidden/);
  const paths = mediaCandidates('/synthetic-msg', image);
  assert.equal(paths[0].path, '/synthetic-msg/attach/2c1743a391305fbf367df8e4f069f9f9/2023-11/Img/' + 'c'.repeat(32) + '_h.dat');
  assert.equal(paths[2].path.endsWith('c'.repeat(32) + '.dat'), true);
  assert.equal(paths[3].quality, 'thumbnail');
  assert.equal(mediaCandidates('/synthetic-msg', { ...image, sourceKind: 'video' })[0].path, '/synthetic-msg/video/2023-11/' + 'c'.repeat(32) + '.mp4');
  console.log('PASS content sources: XML normalization, stable references, time, paging and source scope');
} finally { rmSync(root, { recursive: true, force: true }); }
